#!/usr/bin/env node
// Generates supabase/module_content_seed.sql from content/modules/*.json.
// The JSON files are the source of truth; never edit the seed by hand.
//
//   node scripts/build-module-content-seed.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadModules, topicId } from './module-content-lib.mjs';

const str = (v) => `'${String(v).replace(/'/g, "''")}'`;
const json = (v) => `${str(JSON.stringify(v))}::jsonb`;

const modules = loadModules();
const moduleRows = [];
const topicRows = [];
const quizRows = [];
const topicIds = [];

for (const m of modules) {
  moduleRows.push(`(${[str(m.id), str(m.name), str(m.icon), str(m.description), str(m.audience), m.order].join(', ')})`);
  m.topics.forEach((t, i) => {
    const id = topicId(m.id, t.slug);
    topicIds.push(id);
    topicRows.push(
      `(${[
        str(id), str(m.id), str(t.slug), str(t.title), str(t.icon), str(t.summary),
        json(t.objectives), t.durationMinutes, t.xpReward, json(t.lesson), json(t.reflection),
        t.faithLens ? json(t.faithLens) : 'NULL', i + 1,
      ].join(', ')})`,
    );
    t.quiz.forEach((q, n) => {
      quizRows.push(
        `(${[str(`${id}#${n + 1}`), str(id), n + 1, str(q.question), json(q.options), q.correctIndex, str(q.explanation)].join(', ')})`,
      );
    });
  });
}

const sql = `-- ═══════════════════════════════════════════════════════════════════
-- Harmony Lifestyle Academy — Wellness Module Content Seed
-- GENERATED by scripts/build-module-content-seed.mjs from content/modules/*.json.
-- Do not edit by hand: change the JSON, then regenerate.
--
-- Run supabase/module_content_schema.sql first. This file is idempotent: it
-- upserts every row, so re-running it publishes edited content.
-- ${modules.length} modules, ${topicRows.length} topics, ${quizRows.length} quiz questions
-- ═══════════════════════════════════════════════════════════════════
BEGIN;

INSERT INTO public.wellness_modules (id, name, icon, description, audience, sort_order)
VALUES
${moduleRows.join(',\n')}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name, icon = EXCLUDED.icon, description = EXCLUDED.description,
  audience = EXCLUDED.audience, sort_order = EXCLUDED.sort_order, updated_at = NOW();

INSERT INTO public.module_topics
  (id, module_id, slug, title, icon, summary, objectives, duration_minutes, xp_reward, lesson, reflection, faith_lens, sort_order)
VALUES
${topicRows.join(',\n')}
ON CONFLICT (id) DO UPDATE SET
  module_id = EXCLUDED.module_id, slug = EXCLUDED.slug, title = EXCLUDED.title, icon = EXCLUDED.icon,
  summary = EXCLUDED.summary, objectives = EXCLUDED.objectives, duration_minutes = EXCLUDED.duration_minutes,
  xp_reward = EXCLUDED.xp_reward, lesson = EXCLUDED.lesson, reflection = EXCLUDED.reflection,
  faith_lens = EXCLUDED.faith_lens, sort_order = EXCLUDED.sort_order, updated_at = NOW();

-- Replace the questions of every seeded topic so that removed questions do not linger.
DELETE FROM public.module_quiz_questions
WHERE topic_id IN (${topicIds.map(str).join(', ')});

INSERT INTO public.module_quiz_questions (id, topic_id, sort_order, question, options, correct_index, explanation)
VALUES
${quizRows.join(',\n')};

COMMIT;

-- Verification:
-- SELECT m.id, count(DISTINCT t.id) AS topics, count(q.id) AS questions
-- FROM public.wellness_modules m
-- JOIN public.module_topics t ON t.module_id = m.id
-- JOIN public.module_quiz_questions q ON q.topic_id = t.id
-- GROUP BY m.id, m.sort_order ORDER BY m.sort_order;
`;

const out = join(ROOT, 'supabase', 'module_content_seed.sql');
writeFileSync(out, sql);
console.log(`wrote ${out}: ${modules.length} modules, ${topicRows.length} topics, ${quizRows.length} quiz questions`);
